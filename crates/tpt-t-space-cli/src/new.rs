//! `tpts new <vehicle>` — scaffold a mission crate under `crates/` that is
//! wired to the core Safe Mode controller and the DTN agent, with a smoke
//! test. The workspace picks it up through `crates/*`.

use std::fs;
use std::path::Path;
use std::process::ExitCode;

use crate::{CliResult, flag_value, positional, repo_root};

const VEHICLES: [&str; 3] = ["rover", "satellite", "orbital"];

const CARGO_TEMPLATE: &str = r#"[package]
name = "{NAME}"
version.workspace = true
edition.workspace = true
rust-version.workspace = true
license.workspace = true
authors.workspace = true
repository.workspace = true
description = "{VEHICLE} mission crate for tpt-teleop-space (generated by tpts new)"

[dependencies]
tpt-t-space-core = { workspace = true }
tpt-t-space-dtn = { workspace = true }

[lints]
workspace = true
"#;

const LIB_TEMPLATE: &str = r#"//! {VEHICLE} mission crate — generated by `tpts new {VEHICLE}`.
//!
//! Wired to the workspace's shared safety machinery: the core Safe Mode
//! controller drives the vehicle's actions, and the DTN agent holds
//! telemetry until the link returns. Replace the placeholder actions and
//! payloads with the vehicle's own.

use tpt_t_space_core::safe_mode::{SafeModeActions, SafeModeCause, SafeModeController};
use tpt_t_space_dtn::bundle::{Bundle, BundleStore, EndpointId, Priority};
use tpt_t_space_dtn::link::DtnAgent;

/// The vehicle's Safe Mode actions. Each one drives real hardware in a
/// flight build; here they record what happened.
#[derive(Debug)]
pub struct Actions {
    /// Science and mission payloads are powered.
    pub payloads_on: bool,
    /// The vehicle is slewed to a sun-pointing attitude.
    pub sun_pointing: bool,
    /// Beacon rate, bits per second (0 until Safe Mode starts it).
    pub beacon_bps: u32,
}

impl SafeModeActions for Actions {
    fn shed_payloads(&mut self) {
        self.payloads_on = false;
    }
    fn slew_to_sun_point(&mut self) {
        self.sun_pointing = true;
    }
    fn start_beacon(&mut self, rate_bps: u32) {
        self.beacon_bps = rate_bps;
    }
}

/// The mission: Safe Mode controller, its actions, and the telemetry queue.
pub struct Mission {
    safe_mode: SafeModeController,
    actions: Actions,
    dtn: DtnAgent,
    next_bundle: u64,
}

impl Mission {
    /// A mission with payloads on, no beacon, and an empty 16-sector queue.
    #[must_use]
    pub fn new() -> Self {
        Self {
            safe_mode: SafeModeController::new(),
            actions: Actions {
                payloads_on: true,
                sun_pointing: false,
                beacon_bps: 0,
            },
            dtn: DtnAgent::new(BundleStore::new(16, 1024)),
            next_bundle: 1,
        }
    }

    /// Queue one telemetry frame for downlink. Returns `false` if the store
    /// is full or the frame does not fit a sector.
    pub fn queue_telemetry(&mut self, now_s: u64, frame: &[u8]) -> bool {
        let bundle = Bundle::new(self.next_bundle, EndpointId::EARTH_OPS, now_s, frame.len(), Priority::Normal, 1);
        self.next_bundle += 1;
        self.dtn.store().store_bundle(&bundle, frame).is_ok()
    }

    /// Enter Safe Mode atomically on a power survival trigger.
    pub fn trigger_safe_mode(&mut self, now_s: u64) -> bool {
        self.safe_mode
            .enter(now_s, SafeModeCause::PowerSurvivalThreshold, &mut self.actions)
    }

    /// Telemetry frames waiting for the link.
    #[must_use]
    pub fn pending(&self) -> u32 {
        self.dtn.pending()
    }

    /// The vehicle's current Safe Mode actions.
    #[must_use]
    pub fn actions(&self) -> &Actions {
        &self.actions
    }
}

impl Default for Mission {
    fn default() -> Self {
        Self::new()
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use tpt_t_space_core::safe_mode::SAFE_MODE_BEACON_BPS;

    #[test]
    fn safe_mode_sheds_payloads_and_queues_telemetry() {
        let mut m = Mission::new();
        assert!(m.queue_telemetry(0, b"frame-0"));
        assert_eq!(m.pending(), 1);

        assert!(m.trigger_safe_mode(10));
        assert!(!m.actions().payloads_on);
        assert!(m.actions().sun_pointing);
        assert_eq!(m.actions().beacon_bps, SAFE_MODE_BEACON_BPS);
    }
}
"#;

pub fn run(args: &[String]) -> CliResult {
    let vehicle =
        positional(args, &["--name"]).ok_or("new needs a vehicle: rover, satellite or orbital")?;
    if !VEHICLES.contains(&vehicle) {
        return Err(format!(
            "unknown vehicle `{vehicle}` (expected rover, satellite or orbital)"
        ));
    }
    let name = match flag_value(args, "--name")? {
        Some(n) => n.to_owned(),
        None => format!("tpt-t-space-mission-{vehicle}"),
    };
    validate_name(&name)?;

    let root = repo_root()?;
    let dir = root.join("crates").join(&name);
    if dir.exists() {
        return Err(format!("{} already exists", dir.display()));
    }
    let src = dir.join("src");
    fs::create_dir_all(&src).map_err(|e| format!("{}: {e}", src.display()))?;
    write(
        &dir.join("Cargo.toml"),
        &render(CARGO_TEMPLATE, &name, vehicle),
    )?;
    write(&src.join("lib.rs"), &render(LIB_TEMPLATE, &name, vehicle))?;

    println!("created {}", dir.display());
    println!("next: cargo test -p {name}");
    Ok(ExitCode::SUCCESS)
}

/// Crate names must be lowercase ASCII, digits and hyphens, and start with
/// the workspace prefix so they are easy to find.
fn validate_name(name: &str) -> Result<(), String> {
    let ok = name.starts_with("tpt-t-space-")
        && name.len() <= 64
        && name
            .chars()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-');
    if ok {
        Ok(())
    } else {
        Err(format!(
            "crate name `{name}` must start with `tpt-t-space-` and use only a-z, 0-9, `-`"
        ))
    }
}

fn render(template: &str, name: &str, vehicle: &str) -> String {
    template
        .replace("{NAME}", name)
        .replace("{VEHICLE}", vehicle)
}

fn write(path: &Path, contents: &str) -> Result<(), String> {
    fs::write(path, contents).map_err(|e| format!("{}: {e}", path.display()))
}

#[cfg(test)]
mod tests {
    use super::{CARGO_TEMPLATE, render, validate_name};

    #[test]
    fn names_need_the_workspace_prefix() {
        assert!(validate_name("tpt-t-space-mission-rover").is_ok());
        assert!(validate_name("mission-rover").is_err());
        assert!(validate_name("tpt-t-space-Rover").is_err());
        assert!(validate_name("tpt-t-space-rover_2").is_err());
    }

    #[test]
    fn templates_are_filled_in() {
        let toml = render(CARGO_TEMPLATE, "tpt-t-space-mission-rover", "rover");
        assert!(toml.contains("name = \"tpt-t-space-mission-rover\""));
        assert!(toml.contains("mission crate"));
        assert!(!toml.contains("{NAME}") && !toml.contains("{VEHICLE}"));
    }
}
